@dataclass(frozen=True, slots=True)
class ProductWorld:
    """
    World generated by a dynamic epistemic product update.

    A ProductWorld is a pair:

        (base world, executed event)

    The base Configuration represents the physical world.
    The event represents the epistemic action that occurred.
    """

    world: Configuration
    event: str

    def __repr__(self) -> str:
        return (
            f"ProductWorld("
            f"world={self.world!r}, "
            f"event={self.event!r}"
            f")"
        )


World = Configuration | ProductWorld


def _configuration(
    world: World,
) -> Configuration:
    """
    Extract the underlying physical configuration.
    """

    if isinstance(
        world,
        ProductWorld,
    ):
        return world.world

    return world


