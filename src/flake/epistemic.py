@dataclass(frozen=True, slots=True)
class Knowledge(Formula):
    """
    K_i φ

    Agent i knows φ.
    """

    agent: str
    operand: Formula

    def __post_init__(self) -> None:
        if not self.agent.strip():
            raise ValueError(
                "Knowledge agent must not be empty"
            )

    def __repr__(self) -> str:
        return (
            f"K_{self.agent}({self.operand!r})"
        )


def K(
    agent: str | Agent,
    operand: Formula,
) -> Knowledge:
    """
    Factory for K_i φ.
    """

    name = (
        agent.name
        if isinstance(
            agent,
            Agent,
        )
        else agent
    )

    return Knowledge(
        agent=name,
        operand=operand,
    )


# ============================================================================
# Group operators
# ============================================================================


def _normalize_group(
    agents: (
        str
        | Agent
        | Iterable[str | Agent]
    ),
) -> tuple[str, ...]:
    if isinstance(
        agents,
        Agent,
    ):
        values = (
            agents.name,
        )

    elif isinstance(
        agents,
        str,
    ):
        values = (
            agents,
        )

    else:
        values = tuple(
            agent.name
            if isinstance(
                agent,
                Agent,
            )
            else agent
            for agent in agents
        )

    if not values:
        raise ValueError(
            "An epistemic group must not be empty"
        )

    result: list[str] = []

    for name in values:
        if not isinstance(
            name,
            str,
        ):
            raise TypeError(
                "Agent names must be strings or Agent objects"
            )

        name = name.strip()

        if not name:
            raise ValueError(
                "Agent name must not be empty"
            )

        if name not in result:
            result.append(
                name
            )

    return tuple(result)


@dataclass(frozen=True, slots=True)
class EveryoneKnows(Formula):
    """
    E_A φ

    Every agent in A knows φ.
    """

    agents: tuple[str, ...]
    operand: Formula

    def __repr__(self) -> str:
        group = ",".join(
            self.agents
        )

        return (
            f"E_{{{group}}}({self.operand!r})"
        )


def E(
    agents: (
        str
        | Agent
        | Iterable[str | Agent]
    ),
    operand: Formula,
) -> EveryoneKnows:
    return EveryoneKnows(
        agents=_normalize_group(
            agents
        ),
        operand=operand,
    )


